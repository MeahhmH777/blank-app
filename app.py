import streamlit as st
import google.generativeai as ai

# 1. إعداد واجهة الموقع وتصميمها
st.set_page_config(page_title="فاحص المتاجر والروابط الذكي", page_icon="🛡️", layout="centered")

st.title("🛡️ فاحص المتاجر والروابط الذكي")
st.subheader("تأكد من سلامة الحسابات والروابط قبل التحويل، الحجز، أو الدفع")
st.write("---")

# صندوق إدخال الرابط أو اسم الحساب من المستخدم
user_input = st.text_input(
    "الصق الرابط أو اسم الحساب/المتجر هنا للتحقق منه:", 
    placeholder="مثال: رابط حجز مطعم، رابط شاليه، متجر فساتين، أو رابط دفع وصلك بالرسائل"
)

# 2. إعداد الذكاء الاصطناعي (Gemini)
# ضع مفتاح الـ API الخاص بك هنا
ai.configure(api_key="ضع_مفتاح_الـ_API_هنا")

# الأمر الموجه للذكاء الاصطناعي مخصص لفحص الحسابات والروابط المباشرة
prompt_instructions = f"""
أنت خبير محترف ومخصص في كشف الاحتيال الإلكتروني، والروابط الخبيثة والمتاجر الوهمية. 
مهمتك تحليل النمط أو الرابط أو اسم المتجر المقدم: {user_input}

قم بالتحليل بناءً على معايير الأمان التالية:
1. إذا كان رابط حجز (مطعم، فعاليات، طيران): تحقق هل الرابط يمثل النطاق الرسمي أم رابط صياد (Phishing) يقلد الواجهات لسرقة بيانات البطاقات البنكية.
2. إذا كان حساب/متجر (عبايات، فساتين، شاليهات، منتجعات): تحقق من المعايير الأمنية (وجود سجل تجاري/وثيقة عمل حر، موقع معروف على الخريطة، التحويل لأسماء مجهولة).
3. إذا كان رابط دفع أو رسالة نصية: تحقق من الصيغة والامتداد وعلامات التضليل الشائعة.

أعطني النتيجة باللغة العربية بوضوح:
- النتيجة النهائية في أول سطر بوضوح: (آمن وموثوق) أو (مشبوه وينصح بالحذر) أو (رابط احتيالي/حساب خطير).
- نصائح مخصصة وسريعة للمستخدم للتحقق بنفسه (مثلاً: التأكد من امتداد الموقع، عدم إدخال رموز OTP، أو طلب معاينة الشاليه).
"""

# 3. زر الفحص والتفاعل
if st.button("ابدأ الفحص الذكي الآن", type="primary"):
    if user_input:
        with st.spinner("جاري تحليل الرابط والحساب ومراجعة معايير الأمان..."):
            try:
                model = ai.GenerativeModel("gemini-1.5-flash")
                response = model.generate_content(prompt_instructions)
                result_text = response.text
                
                st.write("### 📊 نتيجة وتقييم الأمان:")
                
                if "آمن" in result_text or "موثوق" in result_text:
                    st.success(result_text)
                    st.balloons()
                elif "مشبوه" in result_text:
                    st.warning(result_text)
                else:
                    st.error(result_text)
                    
            except Exception as e:
                st.error("حدث خطأ أثناء الفحص، تأكد من إعداد مفتاح الـ API بشكل صحيح.")
    else:
        st.info("من فضلك، ضع الرابط أو اسم الحساب أولاً ليتم فصحه.")

st.write("---")
st.caption("جميع الحقوق محفوظة © تطبيق فاحص المتاجر والروابط الذكي 2026")
